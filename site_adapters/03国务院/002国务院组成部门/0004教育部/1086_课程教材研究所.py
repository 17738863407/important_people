def clean_text(value: str) -> str:
    """压缩课程教材研究所页面中的排版空白。"""
    return re.sub(r"[\s\u3000\u00a0\u2002-\u200b]+", "", str(value or "")).strip()


def parse_page(html: str, final_url: str, page_rule: dict[str, object]) -> list[dict[str, str]]:
    """解析主要领导列表。"""
    soup = BeautifulSoup(html, "html.parser")
    organization = str(page_rule.get("organization", ""))
    page_url = str(page_rule.get("url", "")) or final_url
    parser = str(page_rule.get("parser", ""))
    selector_summary = "strategy=custom_parse_page；selector=#organization2 .lbox .item；fields=.name1/.job1"
    rows: list[dict[str, str]] = []
    seen: set[str] = set()

    for item in soup.select("#organization2 .lbox .item"):
        name_node = item.select_one(".name1")
        duty_node = item.select_one(".job1")
        name = clean_text(name_node.get_text(" ", strip=True) if name_node else "")
        duty = clean_text(duty_node.get_text(" ", strip=True) if duty_node else "")
        link_node = item.select_one(".name1 a[href], .job1 a[href]")
        if not re.fullmatch(r"[\u4e00-\u9fa5]{2,4}", name) or not duty:
            continue
        if name in seen:
            continue
        seen.add(name)
        rows.append(
            {
                "organization": organization,
                "url": page_url,
                "name": name,
                "duty": duty,
                "detail_url": urljoin(page_url, str(link_node.get("href", ""))) if link_node else "",
                "evidence": duty,
                "parser": parser,
                "selector_summary": selector_summary,
            }
        )
    return rows


