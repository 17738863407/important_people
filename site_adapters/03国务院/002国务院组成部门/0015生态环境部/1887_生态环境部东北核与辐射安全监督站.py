def _clean_text(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\u3000", " ").replace("\xa0", " ")).strip()


def parse_page(html: str, final_url: str, page_rule: dict) -> list[object]:
    """按TRS正文段落顺序解析“姓名 职务”记录。"""
    from crawler_core.models import PersonRecord

    soup = BeautifulSoup(html, "html.parser")
    records: list[PersonRecord] = []
    seen_names: set[str] = set()
    for item in soup.select(".TRS_Editor p"):
        text = _clean_text(item.get_text(" ", strip=True))
        match = re.fullmatch(r"([\u4e00-\u9fff](?:\s*[\u4e00-\u9fff]){1,3})\s+(.+)", text)
        if match is None:
            continue
        name = re.sub(r"\s+", "", match.group(1))
        duty = _clean_text(match.group(2))
        if name in seen_names or not duty:
            continue
        seen_names.add(name)
        records.append(
            PersonRecord(
                organization=page_rule["organization"],
                url=page_rule["url"],
                name=name,
                duty=duty,
                detail_url="",
                evidence=duty,
                confidence="high",
                parser=page_rule["parser"],
                selector_summary=".TRS_Editor p姓名职务分隔文本",
            )
        )
    return records


