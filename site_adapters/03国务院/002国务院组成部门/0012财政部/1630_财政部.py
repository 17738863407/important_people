def parse_page(html: str, final_url: str, page_rule: dict) -> list[dict[str, str]]:
    """解析财政部部领导列表。"""
    soup = BeautifulSoup(html, "html.parser")
    rows: list[dict[str, str]] = []
    for item in soup.select("ul.bsznBox.bld > li"):
        link = item.select_one("p a[href]")
        duty_node = item.select_one("span a")
        raw_name = link.get_text(" ", strip=True) if link else ""
        name = "".join(raw_name.replace("：", "").replace(":", "").split())
        duty = duty_node.get_text(" ", strip=True) if duty_node else ""
        duty = " ".join(duty.split())
        if not name or not duty:
            continue
        detail_url = urljoin(final_url, str(link.get("href") or "")) if final_url else ""
        rows.append(
            {
                "name": name,
                "duty": duty,
                "detail_url": detail_url,
                "evidence": duty,
                "confidence": "high",
                "parser": "mof_bld_list_v1",
                "selector_summary": "leader=ul.bsznBox.bld > li; name=p a; duty=span a",
            }
        )
    return rows


