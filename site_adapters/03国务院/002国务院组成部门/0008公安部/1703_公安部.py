def clean_text(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\u3000", " ").replace("\xa0", " ")).strip()


def parse_page(html: str, final_url: str, page_rule: dict) -> list[dict]:
    soup = BeautifulSoup(html, "html.parser")
    rows: list[dict] = []
    for block in soup.select(".leftBox.fl > div"):
        lines = [clean_text(line) for line in block.get_text("\n", strip=True).splitlines()]
        lines = [line for line in lines if line]
        if len(lines) < 2:
            continue
        name = lines[0].replace(" ", "")
        duty = clean_text("".join(lines[1:]))
        link = block.select_one("a[href]")
        if not re.fullmatch(r"[\u4e00-\u9fa5]{2,4}", name) or not duty:
            continue
        detail_url = urljoin(final_url, link.get("href", "")) if link else ""
        if detail_url.rstrip("/") == final_url.rstrip("/"):
            detail_url = ""
        rows.append(
            {
                "name": name,
                "duty": duty,
                "detail_url": detail_url,
                "evidence": duty,
                "selector_summary": "公安部.leftBox领导块姓名职务",
            }
        )
    return rows


