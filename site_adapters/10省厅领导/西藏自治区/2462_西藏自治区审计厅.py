def parse_page(html: str, final_url: str, page_rule: dict) -> list:
    """复用既有段落解析，仅删除每条职务末尾对应的姓名。"""
    from crawler_core.parser_registry import parse_with_registered_parser

    records = parse_with_registered_parser(page_rule, html, final_url, None)
    for record in records:
        record.evidence = re.sub(
            rf"\s*[:：]\s*{re.escape(record.name)}\s*$",
            "",
            str(record.evidence or ""),
        ).strip(" ，,。；;：: ")
    return records


def main() -> None:
    """运行当前页面级在线爬虫。"""
    project_dir = resolve_project_dir()
    if str(project_dir) not in sys.path:
        sys.path.insert(0, str(project_dir))

    from crawler_core.runner import run_page_adapter

    output_path = run_page_adapter(PAGE_RULE, globals())
    print(f"输出文件：{output_path}")


if __name__ == "__main__":
    main()
