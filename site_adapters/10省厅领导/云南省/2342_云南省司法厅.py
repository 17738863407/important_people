def clean_text(text: str) -> str:
    """压缩网页文本空白。"""
    return re.sub(r"[\s\u00A0\u3000]+", "", str(text or "")).strip(" ：:，,。；;")


def clean_evidence(text: str) -> str:
    """保留证据句的基本可读空格。"""
    return re.sub(r"[\s\u00A0\u3000]+", " ", str(text or "")).strip()


def parse_page(html: str, final_url: str, page_rule: dict) -> list[dict[str, str]]:
    """解析云南省司法厅领导班子成员分工正文。"""
    soup = BeautifulSoup(html, "html.parser")
    rows: list[dict[str, str]] = []
    seen: set[str] = set()
    for paragraph in soup.select(".activity p"):
        strong = paragraph.find("strong")
        if not strong:
            continue
        head = clean_text(strong.get_text(" ", strip=True))
        match = re.match(r"^(.+(?:书记|厅长|副厅长|局长|主任|组长))([\u4e00-\u9fff]{2,3})同志$", head)
        if not match:
            continue
        duty = match.group(1).strip(" ：:，,。；;")
        name = match.group(2).strip()
        if not name or not duty or name in seen:
            continue
        seen.add(name)
        rows.append(
            {
                "name": name,
                "duty": duty,
                "detail_url": "",
                "evidence": duty,
                "parser": "custom_yunnan_justice_duty_text_v1",
                "selector_summary": ".activity p strong；pattern=职务+姓名同志",
            }
        )
    return rows


