def _clean_text(value: str) -> str:
    return re.sub(r"\s+", " ", value or "").strip(" ，、\t\r\n")


def _clean_name(value: str) -> str:
    return re.sub(r"[\s\u3000]+", "", value or "").strip()


def parse_page(html: str, final_url: str, page_rule: dict) -> list[dict]:
    soup = BeautifulSoup(html, "html.parser")
    rows: list[dict] = []
    seen: set[str] = set()
    for cell in soup.select("td.hanggao45"):
        name_node = cell.select_one("span.weiruan32")
        if not name_node:
            continue
        name = _clean_name(name_node.get_text(" ", strip=True))
        parts = [_clean_text(text) for text in cell.stripped_strings]
        parts = [part for part in parts if part and _clean_name(part) != name]
        duty = _clean_text(" ".join(parts))
        if not name or not duty or name in seen:
            continue
        seen.add(name)
        link = cell.find("a", href=True)
        detail_url = urljoin(final_url, link["href"]) if link else ""
        rows.append(
            {
                "organization": page_rule["organization"],
                "url": page_rule["url"],
                "name": name,
                "duty": duty,
                "detail_url": detail_url,
                "evidence": duty,
                "parser": "custom_tianjin_cppcc_leader_cells_v1",
                "selector_summary": "td.hanggao45 span.weiruan32姓名+同格职务",
            }
        )
    return rows


