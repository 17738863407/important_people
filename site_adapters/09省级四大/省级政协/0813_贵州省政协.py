def clean_text(value: str) -> str:
    """压缩网页文本空白。"""
    text = str(value or "").replace("\u3000", " ").replace("\xa0", " ")
    return re.sub(r"\s+", " ", text).strip()


def parse_page(html: str, final_url: str, page_rule: dict[str, object]) -> list[dict[str, str]]:
    """解析贵州省政协主席、副主席分组。"""
    soup = BeautifulSoup(html, "html.parser")
    source_url = str(page_rule.get("url", "")) or final_url
    rows: list[dict[str, str]] = []
    seen: set[str] = set()

    for group in soup.select(".wyzc-center .fenzu"):
        duty = clean_text(group.get_text(" ", strip=True))
        if duty not in {"主席", "副主席"}:
            continue
        people_list = group.find_next_sibling("ul")
        if people_list is None:
            continue
        for span in people_list.select("li span"):
            name = clean_text(span.get_text(" ", strip=True))
            if name in seen or not re.fullmatch(r"[\u4e00-\u9fff]{2,4}", name):
                continue
            seen.add(name)
            rows.append(
                {
                    "organization": str(page_rule.get("organization", "")),
                    "url": source_url,
                    "name": name,
                    "duty": duty,
                    "detail_url": "",
                    "evidence": duty,
                    "confidence": "high",
                    "parser": str(page_rule.get("parser", "")),
                    "selector_summary": "省政协主席、副主席页面.wyzc-center分组及span姓名",
                }
            )

    return rows


